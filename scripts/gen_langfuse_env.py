"""Generate .env.langfuse (Langfuse server secrets) and put the matching SDK keys in .env.

Run once from the project root:   python scripts/gen_langfuse_env.py
Re-running keeps existing files unless you pass --force (which would make the Langfuse
database unreadable if it already exists - only use it on a fresh install).
"""
from __future__ import annotations

import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LF_ENV = ROOT / ".env.langfuse"
APP_ENV = ROOT / ".env"
PROJECT_ID = "hybrid-rag"


def hexkey(n: int) -> str:
    return secrets.token_hex(n)


def main() -> None:
    force = "--force" in sys.argv
    if LF_ENV.exists() and not force:
        print(f"{LF_ENV.name} already exists - keeping it (use --force on a fresh install only).")
        text = LF_ENV.read_text(encoding="utf-8")
    else:
        pg, ch, redis, minio = (hexkey(16) for _ in range(4))
        pk, sk = f"pk-lf-{hexkey(16)}", f"sk-lf-{hexkey(24)}"
        admin_pw = secrets.token_urlsafe(12)
        text = f"""# Generated by scripts/gen_langfuse_env.py - git-ignored, keep it private.
# ---- Langfuse web + worker ----
NEXTAUTH_URL=http://localhost:3000
NEXTAUTH_SECRET={hexkey(32)}
SALT={hexkey(32)}
ENCRYPTION_KEY={hexkey(32)}
TELEMETRY_ENABLED=false
DATABASE_URL=postgresql://postgres:{pg}@langfuse-postgres:5432/postgres
CLICKHOUSE_MIGRATION_URL=clickhouse://langfuse-clickhouse:9000
CLICKHOUSE_URL=http://langfuse-clickhouse:8123
CLICKHOUSE_USER=clickhouse
CLICKHOUSE_PASSWORD={ch}
CLICKHOUSE_CLUSTER_ENABLED=false
REDIS_HOST=langfuse-redis
REDIS_PORT=6379
REDIS_AUTH={redis}
LANGFUSE_S3_EVENT_UPLOAD_BUCKET=langfuse
LANGFUSE_S3_EVENT_UPLOAD_REGION=auto
LANGFUSE_S3_EVENT_UPLOAD_ACCESS_KEY_ID=minio
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY={minio}
LANGFUSE_S3_EVENT_UPLOAD_ENDPOINT=http://langfuse-minio:9000
LANGFUSE_S3_EVENT_UPLOAD_FORCE_PATH_STYLE=true
LANGFUSE_S3_EVENT_UPLOAD_PREFIX=events/
LANGFUSE_S3_MEDIA_UPLOAD_BUCKET=langfuse
LANGFUSE_S3_MEDIA_UPLOAD_REGION=auto
LANGFUSE_S3_MEDIA_UPLOAD_ACCESS_KEY_ID=minio
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY={minio}
LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT=http://localhost:9090
LANGFUSE_S3_MEDIA_UPLOAD_INTERNAL_ENDPOINT=http://langfuse-minio:9000
LANGFUSE_S3_MEDIA_UPLOAD_FORCE_PATH_STYLE=true
LANGFUSE_S3_MEDIA_UPLOAD_PREFIX=media/
# ---- headless init: org, project, API keys and first user are created on first start ----
LANGFUSE_INIT_ORG_ID=local-org
LANGFUSE_INIT_ORG_NAME=Local
LANGFUSE_INIT_PROJECT_ID={PROJECT_ID}
LANGFUSE_INIT_PROJECT_NAME=Hybrid RAG
LANGFUSE_INIT_PROJECT_PUBLIC_KEY={pk}
LANGFUSE_INIT_PROJECT_SECRET_KEY={sk}
LANGFUSE_INIT_USER_EMAIL=admin@example.com
LANGFUSE_INIT_USER_NAME=Admin
LANGFUSE_INIT_USER_PASSWORD={admin_pw}
# ---- backing services ----
POSTGRES_USER=postgres
POSTGRES_PASSWORD={pg}
POSTGRES_DB=postgres
MINIO_ROOT_USER=minio
MINIO_ROOT_PASSWORD={minio}
"""
        LF_ENV.write_text(text, encoding="utf-8")
        print(f"Wrote {LF_ENV.name}")

    values = dict(re.findall(r"^([A-Z0-9_]+)=(.*)$", text, re.M))
    sdk = {
        "LANGFUSE_PUBLIC_KEY": values["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": values["LANGFUSE_INIT_PROJECT_SECRET_KEY"],
        "LANGFUSE_PROJECT_ID": values["LANGFUSE_INIT_PROJECT_ID"],
    }
    if not APP_ENV.exists():
        APP_ENV.write_text((ROOT / ".env.example").read_text(encoding="utf-8"), encoding="utf-8")
        print("Created .env from .env.example - add HF_TOKEN and GOOGLE_API_KEY to it.")
    env = APP_ENV.read_text(encoding="utf-8")
    for key, val in sdk.items():
        if re.search(rf"^{key}=.*$", env, re.M):
            env = re.sub(rf"^{key}=.*$", f"{key}={val}", env, flags=re.M)
        else:
            env += f"\n{key}={val}\n"
    APP_ENV.write_text(env, encoding="utf-8")
    print("Updated LANGFUSE_PUBLIC_KEY / LANGFUSE_SECRET_KEY / LANGFUSE_PROJECT_ID in .env")
    print(f"Langfuse login: {values['LANGFUSE_INIT_USER_EMAIL']} / "
          f"{values['LANGFUSE_INIT_USER_PASSWORD']}   (http://localhost:3000)")


if __name__ == "__main__":
    main()
